const normKey = (s: string) => s.replace(/\s+/g, "");

/**
 * 약칭이면 정식 법령명으로 확장, 아니면 입력 그대로 반환.
 * ("화관법" → "화학물질관리법", "근로기준법" → "근로기준법")
 */
